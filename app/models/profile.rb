  def attach_audio_bytes(attachment, bytes, filename)
    tempfile = Tempfile.new([filename, ".mp3"])
    tempfile.binmode
    tempfile.write(bytes)
    tempfile.rewind

    attachment.attach(
      io: tempfile,
      filename: filename,
      content_type: "audio/mpeg",
    )
  ensure
    tempfile.close! if tempfile
  end
