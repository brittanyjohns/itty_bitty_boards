  # Options a parent may still HAVE but is no longer OFFERED.
  #
  # sanitize_care_settings is a before_save, so it re-cleans the whole care blob
  # every time a profile is saved for ANY reason — an avatar upload is enough.
  # That means deleting an option from CARE_SECTIONS doesn't just stop offering
  # it: it silently erases that answer from every profile still holding it, the
  # next time anything touches them. No error, no 422, and nothing left to
  # restore from.
  #
  # So retiring an option is two steps, not one:
  #
  #   1. Move the key here. The sanitizer keeps ACCEPTING it, so stored answers
  #      survive, and the editor stops OFFERING it (care_registry_view omits
  #      deprecated keys). Nobody new can pick it; nobody loses what they wrote.
  #   2. Once `rake care:remap_options` has moved the stored answers onto their
  #      replacements — and the reports say zero remain — delete the entry here.
  #
  # A rename is a remove plus an add: deprecate the old key, add the new one,
  # and map old => new below.
  #
  # Shape: { "section" => { "field" => { "old_option" => "new_option_or_nil" } } }
  # A nil replacement means "no equivalent — drop it on remap", which still only
  # happens when someone deliberately runs the task.
  #
  # Empty on purpose, and NOT because nothing has ever been cut. The reshape
  # that dropped echolalia, the help-level scales, and the per-section notes
  # fields landed BEFORE the feature was announced, when no profile held a
  # single care answer, so there was nothing to protect and the options were
  # deleted outright. That is a one-time licence which has now expired: every
  # later change has to go back through the two steps above.
  DEPRECATED_CARE_OPTIONS = {}.freeze

  def self.retired_care_options(section_key, field)
    DEPRECATED_CARE_OPTIONS.dig(section_key, field[:key])&.keys || []
  end

  # Every option the SANITIZER will accept: everything in the registry, plus
  # anything already lifted out of it but not yet migrated. A union rather than
  # a sum, so it holds whether the key is still listed in CARE_SECTIONS or not.
  def self.accepted_care_options(section_key, field)
    (field[:options] || []) | retired_care_options(section_key, field)
  end

  # What the editor should OFFER — the registry minus anything retired. Doing
  # the subtraction here is what makes retirement a ONE-line edit: add the key
  # to DEPRECATED_CARE_OPTIONS and it stops being offered while staying
  # acceptable. Deleting it from CARE_SECTIONS in the same breath is exactly the
  # move that destroys stored answers, so don't make that the required step.
  def self.offered_care_options(section_key, field)
    (field[:options] || []) - retired_care_options(section_key, field)
  end

  # The care schema as the editor needs it — the whole registry, its caps, and
  # the custom-key format, in one payload.
  #
  # This lives beside CARE_SECTIONS deliberately. The frontend used to carry a
  # hand-copied duplicate of every option key, and sanitize_care_settings drops
  # an unrecognized key rather than rejecting it — so a rename here silently
  # deleted the parent's answer on their next save, with no error and no 422.
  # Serving the registry means a change to the constant reaches the editor
  # without a frontend deploy, and there is no second copy to drift.
  #
  # Sections are an ARRAY, not a hash: CARE_SECTIONS is insertion-ordered and
  # that order is the order the editor renders in.
  #
  # Labels ride along too, resolved through CareLabels — the backend owns the
  # display strings as well as the schema now, so a server-rendered care sheet
  # and the on-screen card read identically and there is no second copy to
  # drift. See config/locales/care.en.yml.
  #
  # LABELS ARE ADDITIVE, AND MUST STAY THAT WAY. `options` is an array of plain
  # STRINGS and has to remain one: the deployed frontend parses it with
  # `asStringList(field?.options)` (src/data/careSections.ts), which yields []
  # for an array of objects — every section would silently lose its choices and
  # fall back to the bundled copy. So labels arrive as SIBLING keys (`label`,
  # `option_labels`) that an older client simply ignores.
  def self.care_registry_view(locale: I18n.locale)
    {
      locale: locale.to_s,
      sections: CARE_SECTIONS.map do |key, spec|
        {
          key: key,
          label: CareLabels.section(key, locale: locale),
          fields: spec[:fields].map do |field|
            out = {
              key: field[:key],
              type: field[:type],
              label: CareLabels.field(key, field[:key], locale: locale),
            }
            if field[:options]
              # Offered, not accepted: a retired option stays valid on save but is
              # never presented as a fresh choice.
              out[:options] = offered_care_options(key, field)
              # Labels, though, cover ACCEPTED — offered plus retired. A retired
              # option is still stored on real profiles and still has to render;
              # it just must never be offered. So this map is deliberately the
              # wider of the two.
              out[:option_labels] = CareLabels.options_map(key, field, locale: locale)
            end
            out
          end,
        }
      end,
      limits: {
        max_custom_sections: MAX_CUSTOM_CARE_SECTIONS,
        max_custom_items: MAX_CARE_CUSTOM_ITEMS,
        max_multi_select: MAX_CARE_MULTI_SELECT,
        title_max: CARE_TITLE_MAX,
        item_label_max: CARE_ITEM_LABEL_MAX,
        item_value_max: CARE_ITEM_VALUE_MAX,
        short_text_max: CARE_SHORT_TEXT_MAX,
      },
      custom_key_format: js_custom_key_format,
    }
  end

  # Ruby anchors \A and \z are not valid in a JavaScript RegExp, so translate
  # rather than shipping Regexp#source raw — a consumer that compiled it would
  # throw. Derived from the constant on purpose: a hand-written copy of the
  # pattern is exactly the kind of duplicate this endpoint exists to remove.
  def self.js_custom_key_format
    CARE_CUSTOM_KEY_FORMAT.source.sub('\A', "^").sub('\z', "$")
  end

